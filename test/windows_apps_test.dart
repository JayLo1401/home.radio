import 'dart:convert';

import 'package:flutter_test/flutter_test.dart';
import 'package:home_system/data/models/launcher_group.dart';
import 'package:home_system/data/models/launcher_tile.dart';
import 'package:home_system/data/services/desktop/windows_apps.dart';

void main() {
  group('Windows apps', () {
    test('Start menu entries: apps kept, uninstallers, help, readmes and websites left out', () {
      bool app(String name, String target) => isWindowsAppEntry(name, target);
      expect(app('VLC media player', r'{6D809377-6AF0-444B-8957-A3773F02200E}\VideoLAN\VLC\vlc.exe'), isTrue);
      expect(app('Editor', 'Microsoft.WindowsNotepad_8wekyb3d8bbwe!App'), isTrue);
      expect(app('Flatout 3', 'steam://rungameid/201510'), isTrue);
      expect(app('Google Chrome', 'Chrome'), isTrue);
      expect(app('Aufgabenplanung', 'Microsoft.AutoGenerated.{55D5D3DE-E881-C54C-594E-E82D448367FE}'), isTrue);

      expect(app('Uninstall ASUS CPU-Z', r'{6D809377}\CPUID\ASUS CPU-Z\unins000.exe'), isFalse);
      expect(app('Die Völker Gold Edition deinstallieren', 'Microsoft.AutoGenerated.{AC36}'), isFalse);
      expect(app('QtdSync entfernen', r'{7C5A}\QtdSync\x.exe'), isFalse);
      expect(app('7-Zip Help', r'{6D80}\7-Zip\7-zip.chm'), isFalse);
      expect(app('TreeSize Free Hilfe', r'{6D80}\TreeSize\x.exe'), isFalse);
      expect(app('ReadMe-Datei', r'{7C5A}\Cossacks\README.TXT'), isFalse);
      expect(app('Caesar III Website', 'Microsoft.AutoGenerated.{DC29}'), isFalse);
      expect(app('Kundendienst', r'D:\Games\Support\Kundendienst.rtf'), isFalse);
      expect(app('Benutzerhandbuch (PDF, English)', r'{6D80}\Oracle\VirtualBox\doc\UserManual.pdf'), isFalse);
      expect(app('Steam Support Center', 'http://support.steampowered.com/'), isFalse);
      expect(app('www.cdv.de', r'{7C5A}\Cossacks\cdv.url'), isFalse);
      expect(app('Git Release Notes', r'{6D80}\Git\ReleaseNotes.html'), isFalse);
      expect(app('Home System', r'{6D80}\Home System\home_system.exe'), isFalse);
      expect(app('', 'Chrome'), isFalse);
    });

    test('Get-StartApps JSON: filtered, each AppID once, sorted by name', () {
      final json = jsonEncode([
        {'n': 'VLC media player', 'id': r'{6D80}\VideoLAN\VLC\vlc.exe'},
        {'n': 'audacity', 'id': r'{6D80}\Audacity\Audacity.exe'},
        {'n': 'Uninstall', 'id': r'D:\Games\uninstall.exe'},
        {'n': 'Editor', 'id': 'Microsoft.WindowsNotepad_8wekyb3d8bbwe!App'},
        {'n': 'Editor (again)', 'id': 'microsoft.windowsnotepad_8wekyb3d8bbwe!app'},
        {'n': 42, 'id': 'broken'},
      ]);
      final apps = parseStartApps(json);
      expect(apps.map((a) => a.label), ['audacity', 'Editor', 'VLC media player']);
      expect(apps[1].package, 'win:Microsoft.WindowsNotepad_8wekyb3d8bbwe!App');
      expect(apps.every((a) => !a.tv), isTrue);
    });

    test('Get-StartApps JSON: one app as an object, junk and nothing', () {
      expect(parseStartApps('{"n": "Excel", "id": "Microsoft.Office.EXCEL.EXE.15"}').single.package,
          'win:Microsoft.Office.EXCEL.EXE.15');
      expect(parseStartApps('{"Name": "Word", "AppID": "Microsoft.Office.WINWORD.EXE.15"}').single.label, 'Word');
      expect(parseStartApps(''), isEmpty);
      expect(parseStartApps('[]'), isEmpty);
      expect(parseStartApps('not json'), isEmpty);
    });

    test('Internet shortcut: the URL line', () {
      expect(internetShortcutUrl('[InternetShortcut]\r\nIDList=\r\nURL=steam://rungameid/933110\r\nIconIndex=0'),
          'steam://rungameid/933110');
      expect(internetShortcutUrl('[InternetShortcut]\nurl = x'), isNull);
      expect(internetShortcutUrl(''), isNull);
    });

    test('ids: Windows apps, Android packages and where they belong', () {
      expect(isWindowsAppId('win:Chrome'), isTrue);
      expect(isWindowsAppId(r'lnk:C:\ProgramData\Microsoft\Windows\Start Menu\Programs\Audacity.lnk'), isTrue);
      expect(isWindowsAppId('com.netflix.ninja'), isFalse);

      expect(appIdBelongsHere('com.netflix.ninja', android: true, windows: false), isTrue);
      expect(appIdBelongsHere('win:Chrome', android: true, windows: false), isFalse);
      expect(appIdBelongsHere('win:Chrome', android: false, windows: true), isTrue);
      expect(appIdBelongsHere('com.netflix.ninja', android: false, windows: true), isFalse);
      expect(appIdBelongsHere('win:Chrome', android: false, windows: false), isFalse);
      expect(appIdBelongsHere('', android: true, windows: false), isFalse);
    });

    test('Windows app tiles survive the round trip next to Android ones', () {
      const tiles = [
        LauncherTile.radio(),
        LauncherTile.app(package: 'win:Microsoft.WindowsNotepad_8wekyb3d8bbwe!App', label: 'Editor'),
        LauncherTile.app(package: 'com.netflix.ninja', label: 'Netflix'),
      ];
      final back = decodeLauncherTiles(encodeLauncherTiles(tiles));
      expect(back.map((t) => t.id), [
        'radio',
        'app:win:Microsoft.WindowsNotepad_8wekyb3d8bbwe!App',
        'app:com.netflix.ninja',
      ]);
      final groups = decodeLauncherGroups(encodeLauncherGroups([
        LauncherGroup(id: 'g1', name: 'Spiele', tiles: [tiles[1], tiles[2]]),
      ]));
      expect(groups.single.tiles.map((t) => t.package), [tiles[1].package, tiles[2].package]);
    });

    test('icon file names: stable, distinct, file-system safe', () {
      final a = windowsAppIconFileName('win:Chrome');
      expect(a, windowsAppIconFileName('win:Chrome'));
      expect(a, isNot(windowsAppIconFileName('win:chrome')));
      expect(a, matches(RegExp(r'^[0-9a-f]{16}\.png$')));
      // FNV-1a 64 of the empty string.
      expect(windowsAppIconFileName(''), 'cbf29ce484222325.png');
    });

    test('PowerShell: quoting and -EncodedCommand', () {
      expect(powerShellQuote(r"C:\Users\O'Brien\x.txt"), r"'C:\Users\O''Brien\x.txt'");
      // "dir" in UTF-16LE.
      expect(powerShellEncode('dir'), base64.encode([0x64, 0, 0x69, 0, 0x72, 0]));
      expect(base64.decode(powerShellEncode('ä')), [0xE4, 0]);
    });
  });
}
